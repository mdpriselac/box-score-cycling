def test_the_page_carries_the_publishable_key_and_the_project_url(page):
    assert PUBLISHABLE in page and URL in page


def test_the_page_carries_no_secret(mod):
    """A secret key would hand a browser service_role, which bypasses RLS."""
    page = mod.build_html(URL, PUBLISHABLE, local=False, project_ref="abc123")
    assert "sb_secret_" not in page
    assert "service_role" not in page
    assert "SUPABASE_SECRET_KEY" not in page


def test_the_builder_refuses_a_secret_key(mod, tmp_path, capsys):
    out = tmp_path / "ops.html"
    code = mod.main(["--url", URL, "--key", SECRET, "--out", str(out)])
    assert code == 2
    assert "publishable" in capsys.readouterr().err.lower()
    assert not out.exists()


