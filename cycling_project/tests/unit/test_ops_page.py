"""The operator inbox page and the guards that keep it off the public site.

Spec: NIGHTLY_AGENT_WORKFLOW.md §2.7. The page is generated by
``netlify_site/build/build_ops_page.py``, holds only the publishable key, and
is excluded from the deployed site twice over (``.assetsignore`` plus a Worker
guard). These tests are offline: they render the page and read the guards.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

import pytest

from cycling_project.nightly.day_key_record import FORBIDDEN_ITEMS, MENU_ITEMS

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[3]
SITE = ROOT / "netlify_site"
BUILDER = SITE / "build" / "build_ops_page.py"

URL = "https://example-project.supabase.co"
PUBLISHABLE = "sb_publishable_TESTKEYTESTKEYTESTKEY"
SECRET = "sb_secret_TESTKEYTESTKEYTESTKEY"


@pytest.fixture(scope="module")
def mod():
    sys.path.insert(0, str(SITE / "build"))
    spec = importlib.util.spec_from_file_location("build_ops_page", BUILDER)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


@pytest.fixture(scope="module")
def page(mod):
    return mod.build_html(URL, PUBLISHABLE, local=False, project_ref="abc123")


