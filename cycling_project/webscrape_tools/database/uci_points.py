def get_actual_uci_place_points(place: int|str, race_type: str, race_level: str, fc_race_id: int) -> int:
    """
    Get the points for a given place, race type, and race level.
    Raises ValueError when not given correct valeus for race_type and race_level
    Args:
        place (int|str): The rider's finishing place
        race_type (str): The type of race ('gc', 'stage', 'one_day')
        race_level (str): The level of the race tour ('wt', 'pro', 'd1')
        fc_race_id (int): the race ID
    Returns:
        int: The points for the given place, race type, race level, and race ID
    """
    # Convert place to integer if it's a string, returning 0 if it's not an integer
    try:
        place = int(place)
    except ValueError:
        return 0
    # Check the race_level
    race_level = race_level.lower().strip()
    if race_level not in ['wt', 'pro', 'd1']:
        return ValueError("Expected one of 'wt', 'pro', or 'd1' for race_level")
    
    # Check the race_type
    race_type = race_type.lower().strip()
    if race_type not in ['gc', 'stage', 'one_day']:
        return ValueError("Expected one of 'gc', 'stage', or 'one_day' for race_type")
    
    # Get d1 points first
    if race_level == 'd1':
        if race_type == 'gc' or race_type == 'one_day':
            return d1_gc_one_day_points.get(place, 0)
        elif race_type == 'stage':
            return d1_stage_points.get(place, 0)
    
    # Get pro points
    if race_level == 'pro':
        if race_type == 'gc' or race_type == 'one_day':
            return pro_gc_one_day_points.get(place, 0)
        elif race_type == 'stage':
            return pro_stage_points.get(place, 0)

    # Get wt points
    if race_level == 'wt':
        #Get the race tier from the race id
        race_tier = wt_race_tiers.get(fc_race_id, 0)
        #Check stage first
        if race_type == 'stage':
            # Get the stage points using the fc_race_id
            return wt_tier_stage_points.get(race_tier, {}).get(place, 0)
        #If it isn't stage, it must be gc or one_day
        else:
            # Get the tier from the
            return wt_tier_gc_one_day_points.get(race_tier, {}).get(place, 0)

    print(f"Unexpected result for place: {place}, race_type: {race_type}, race_id: {fc_race_id}, race_level: {race_level}")


default_discount_dict = {
    'wt_t1': 1.0,
    'wt_t2': 0.9,
    'wt_t3': 1.0,
    'wt_t4': 0.75,
    'wt_t5': 0.6,
    'pro': 0.4,
    'd1': 0.2
}
    
def get_top_tier_based_points(place: int|str, race_type: str, race_level: str, fc_race_id: int, discount_dict: dict=default_discount_dict) -> int|float:
    """
    Get the points for a given place not as the UCI actually gives points but by discounting the top tier points of a wt race. This gives greater coverage for places and rewards points further down the list than the actual UCI point system.
    Can pass in a place discounting scheme. This will discount To do so you need a dictionary that maps tiers to percentages as a float with the following tiers carved out (these are the default settings):
    
    {wt_t1: 1.0, (this is the Tour de France)
    wt_t2: 0.9, (these are the Giro and Vuelta)
    wt_t3: 1.0, (these are the Monuments)
    wt_t4: 0.75, (Major non monumnet classics and the biggest one week tours)
    wt_t5: 0.5, (Smaller WT one week tours and one days)
    pro: 0.4,
    d1: 0.2}
    
    Raises ValueError when not given correct valeus for race_type and race_level
    Args:
        place (int|str): The rider's finishing place
        race_type (str): The type of race ('gc', 'stage', 'one_day')
        race_level (str): The level of the race tour ('wt', 'pro', 'd1')
        fc_race_id (int): the race ID
        discount_dict (dict): A dictionary that maps tiers to percentages as a float.
    Returns:
        int: The points for the given place, race type, race level, and race ID"""
    # Convert place to integer if it's a string, returning 0 if it's not an integer
    try:
        place = int(place)
    except ValueError:
        return 0
    
    # Check the race_level
    if race_level.strip().lower() not in ['wt', 'pro', 'd1']:
        raise ValueError("Expected one of 'wt', 'pro', or 'd1'")
    # Check the race_type
    if race_type.strip().lower() not in ['gc', 'stage', 'one_day']:
        raise ValueError("Expected one of 'gc', 'stage', or 'one_day'")
    
    # Get the raw points using the t1 points
    if race_type == 'stage':
        raw_points = wt_t1_stage_points.get(place, 0)
    else:
        raw_points = wt_t1_gc_one_day_points.get(place, 0)
    
    if raw_points == 0:
        return 0
    # If the place is not in the points, return 0
    #Apply the appropriate discount, starting with d1
    if race_level == 'd1':
        try:
            return raw_points * discount_dict['d1']
        except:
            raise ValueError("Expected a discount for d1 in the discount_dict in the form of {'d1': 0.2} or some other float value")
    # If not d1, check for pro
    elif race_level == 'pro':
        try:
            return raw_points * discount_dict['pro']
        except:
            raise ValueError("Expected a discount for pro in the discount_dict in the form of {'pro': 0.4} or some other float value")
    # If not pro, it must be wt. Look up the tier of the race first
    else:
        #Check that the race_id is an int
        try:
            race_id_int = int(fc_race_id)
        except ValueError:
            raise ValueError("Expected a valid integer for fc_race_id")
        try:
            race_tier = wt_race_tiers[race_id_int]
        except KeyError:
            raise ValueError(f"Expected a valid WT fc_race_id, but got {fc_race_id} which is not in our list of World Tour Race IDs")
        try: 
            return raw_points * discount_dict[f'wt_t{race_tier}']
        except:
            raise ValueError(f"Expected a discount for wt_t{race_tier} in the discount_dict in the form of {{'wt_t{race_tier}': 0.9}} or some other float value")


